     * Parameterized lookup: dictionary values may contain %s placeholders,
     * substituted positionally by [args]. Locale switch recomposes live.
     */
    fun t(key: Key, vararg args: Any): String {
        val s = t(key)
        if (args.isEmpty()) return s
        var i = 0
        return Regex("%s").replace(s) { args.getOrNull(i++)?.toString() ?: it.value }
    }

    fun t(key: Key): String = when (current) {
        Code.RU -> ru.getValue(key)
        Code.EN -> en[key] ?: ru.getValue(key)
        Code.UK -> uk[key] ?: ru.getValue(key)
        Code.PL -> pl[key] ?: ru.getValue(key)
        Code.DE -> de[key] ?: ru.getValue(key)
    }

