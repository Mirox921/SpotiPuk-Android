    var current by mutableStateOf(Code.RU)
        private set

    fun load(context: Context) {
        val saved = AppPrefs.prefs(context).getString(KEY, null)
        current = Code.entries.firstOrNull { it.code == saved } ?: Code.RU
    }

    fun set(context: Context, code: Code) {
        AppPrefs.prefs(context).edit().putString(KEY, code.code).apply()
        current = code
    }

